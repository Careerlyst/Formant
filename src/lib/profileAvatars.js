export function getProfileAvatarAgeCategory(avatar) {
  return PROFILE_AVATAR_CATEGORY_BY_ID[Number(avatar?.id)] || null;
}

export function getProfileAvatarsByAgeCategory(category = 'all') {
  if (category === 'all') return PROFILE_AVATARS;
  if (!PROFILE_AVATAR_AGE_CATEGORIES.some((item) => item.id === category)) return [];
  return PROFILE_AVATARS.filter((avatar) => getProfileAvatarAgeCategory(avatar) === category);
}

const avatarById = new Map(PROFILE_AVATARS.map((avatar) => [avatar.id, avatar]));

export function getProfileAvatar(value) {
  if (value === null || value === undefined || value === '') return null;
  const id = Number(value);
  return Number.isSafeInteger(id) ? avatarById.get(id) || null : null;
}

export function getFallbackProfileAvatar() {
  return PROFILE_AVATARS[0] || null;
}

export function requiresProfileAvatar(avatarId, isVerifiedStaff = false) {
  return !isVerifiedStaff && !getProfileAvatar(avatarId);
}

const PENDING_AVATAR_KEY = 'formant_pending_avatar_selection_v1';
const PENDING_AVATAR_MAX_AGE = 30 * 24 * 60 * 60 * 1000;

export function savePendingAvatarSelection(email, avatarId, { flowId = '', source = 'email' } = {}) {
  const avatar = getProfileAvatar(avatarId);
  if (!avatar || typeof localStorage === 'undefined') return false;
  try {
    localStorage.setItem(PENDING_AVATAR_KEY, JSON.stringify({
      email: String(email || '').trim().toLowerCase(),
      avatarId: avatar.id,
      flowId: String(flowId || ''),
      source,
      savedAt: Date.now()
    }));
    return true;
  } catch {
    return false;
  }
}

export function getPendingAvatarSelection(email = '', { flowId = '' } = {}) {
  if (typeof localStorage === 'undefined') return null;
  try {
    const pending = JSON.parse(localStorage.getItem(PENDING_AVATAR_KEY) || 'null');
    const savedAt = Number(pending?.savedAt);
    if (!pending || !Number.isFinite(savedAt) || Date.now() - savedAt > PENDING_AVATAR_MAX_AGE) return null;
    if (!getProfileAvatar(pending.avatarId)) return null;
    if (flowId && pending.flowId !== flowId) return null;
    const requestedEmail = String(email || '').trim().toLowerCase();
    if (requestedEmail && pending.email !== requestedEmail) return null;
    return pending;
  } catch {
    return null;
  }
}

export function clearPendingAvatarSelection() {
  try { localStorage.removeItem(PENDING_AVATAR_KEY); } catch { /* Storage may be unavailable. */ }
}
